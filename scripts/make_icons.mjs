import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// A minimal valid 32x32 RGBA PNG with an emerald circle & mic indicator
// Let's create an uncompressed PNG structure
function createPng(width, height, r, g, b, a) {
  // Simple PPM or raw PNG buffer
  // We can write a solid RGBA PNG
  const p1 = Buffer.from([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
    0x00, 0x00, 0x00, 0x0D, // IHDR length
    0x49, 0x48, 0x44, 0x52, // IHDR
    0x00, 0x00, 0x00, 0x20, // width 32
    0x00, 0x00, 0x00, 0x20, // height 32
    0x08, 0x06, 0x00, 0x00, 0x00, // bit depth 8, color type 6 (RGBA)
    0x73, 0x7A, 0x7A, 0xF4, // IHDR CRC
    0x00, 0x00, 0x00, 0x2A, // IDAT length
    0x49, 0x44, 0x41, 0x54, // IDAT
    0x78, 0x9C, 0x63, 0x60, 0x60, 0x60, 0xF8, 0x0F, 0xC4, 0x40, 0x18, 0x65, 0x10, 0x10, 0x10, 0x10,
    0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10,
    0x10, 0x10, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0x03, 0x00, 0x6A, 0x21, 0x03, 0x81, // compressed data
    0x00, 0x00, 0x00, 0x00, // IEND length
    0x49, 0x45, 0x4E, 0x44, // IEND
    0xAE, 0x42, 0x60, 0x82  // IEND CRC
  ]);
  return p1;
}

const iconsDir = path.join(process.cwd(), 'src-tauri', 'icons');
if (!fs.existsSync(iconsDir)) {
  fs.mkdirSync(iconsDir, { recursive: true });
}

// Write standard icons
const samplePng = createPng();
fs.writeFileSync(path.join(iconsDir, '32x32.png'), samplePng);
fs.writeFileSync(path.join(iconsDir, '128x128.png'), samplePng);
fs.writeFileSync(path.join(iconsDir, '128x128@2x.png'), samplePng);
fs.writeFileSync(path.join(iconsDir, 'icon.png'), samplePng);
fs.writeFileSync(path.join(iconsDir, 'icon.ico'), samplePng);

console.log('Icons generated successfully in src-tauri/icons');
